package com.tripdirect.ui.screens.planner

import android.content.Context
import android.content.Intent
import android.widget.Toast
import androidx.compose.animation.*
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.filled.ArrowBack
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import com.tripdirect.data.model.*
import com.tripdirect.ui.screens.trips.SelfPlanVsPackageCard
import com.tripdirect.ui.screens.trips.shareTripSummary
import com.tripdirect.viewmodel.TripPlannerViewModel
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AITripPlannerScreen(
    viewModel: TripPlannerViewModel,
    onNavigateBack: () -> Unit = {},
    onGenerate: () -> Unit = {},
    onNavigateToComparison: () -> Unit = {},
    onNavigateToSafety: () -> Unit = {}
) {
    val context = LocalContext.current

    // Input States
    var destination by remember { mutableStateOf("Ooty") }
    var startDate by remember { mutableStateOf("20 Aug 2026") }
    var endDate by remember { mutableStateOf("23 Aug 2026") }
    var adultsCount by remember { mutableStateOf(2) }
    var childrenCount by remember { mutableStateOf(0) }
    var budget by remember { mutableStateOf("₹10,000") }
    val selectedPreferences = remember { mutableStateOf(setOf("Nature", "Food", "Photography")) }
    var selectedStyle by remember { mutableStateOf("Balanced") }

    // Loading & Generated State
    var isGenerating by remember { mutableStateOf(false) }
    var isPlanGenerated by remember { mutableStateOf(false) }

    // Dialog Visibility States
    var showDatePicker by remember { mutableStateOf(false) }
    var showBudgetEstimator by remember { mutableStateOf(false) }
    var showRouteFinder by remember { mutableStateOf(false) }
    var showStayRecommender by remember { mutableStateOf(false) }
    var showFoodRecommender by remember { mutableStateOf(false) }
    var showWeather by remember { mutableStateOf(false) }
    var showLocalInsights by remember { mutableStateOf(false) }
    var showPackingList by remember { mutableStateOf(false) }
    var showLanguageHelper by remember { mutableStateOf(false) }
    var showCurrencyConverter by remember { mutableStateOf(false) }
    var showOfflinePlan by remember { mutableStateOf(false) }
    var showChatDialog by remember { mutableStateOf(false) }

    val datePickerState = rememberDatePickerState()

    // Sample Data
    val popularItineraries = listOf(
        PopularItinerary("1", "Kerala Escape", "5 Days • 4 Nights", "₹12,500", AIPlannerImages.KERALA, "Kerala"),
        PopularItinerary("2", "Ooty Getaway", "3 Days • 2 Nights", "₹7,800", AIPlannerImages.OOTY, "Ooty"),
        PopularItinerary("3", "Goa Beach Trip", "4 Days • 3 Nights", "₹9,200", AIPlannerImages.GOA, "Goa"),
        PopularItinerary("4", "Hampi Heritage", "3 Days • 2 Nights", "₹6,900", AIPlannerImages.HAMPI, "Hampi")
    )

    val quickTools = listOf(
        QuickToolItem("AI Trip Planner", "✨") { isPlanGenerated = false },
        QuickToolItem("Budget Estimator", "₹") { showBudgetEstimator = true },
        QuickToolItem("Best Route Finder", "🗺") { showRouteFinder = true },
        QuickToolItem("Stay Recommender", "🏨") { showStayRecommender = true },
        QuickToolItem("Food Recommender", "🍴") { showFoodRecommender = true }
    )

    val smartTools = listOf(
        SmartToolItem("1", "Weather Forecast", "🌤", "Live/Demo forecast") { showWeather = true },
        SmartToolItem("2", "Local Insights", "💡", "Customs & Daily budget") { showLocalInsights = true },
        SmartToolItem("3", "Packing List", "🧳", "Suggested items") { showPackingList = true },
        SmartToolItem("4", "Travel Tips", "ℹ", "AI travel advice") { showLocalInsights = true },
        SmartToolItem("5", "Language Helper", "🌐", "Common phrases") { showLanguageHelper = true },
        SmartToolItem("6", "Currency Converter", "💱", "Demo conversion") { showCurrencyConverter = true },
        SmartToolItem("7", "Safety Guide", "🛡", "Emergency assistance") { onNavigateToSafety() },
        SmartToolItem("8", "Offline Plan", "☁", "Save locally") { showOfflinePlan = true }
    )

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("AI Planner ✨", fontWeight = FontWeight.Bold) },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                }
            )
        }
    ) { paddingValues ->
        Box(modifier = Modifier.padding(paddingValues)) {
            LazyColumn(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(horizontal = 16.dp),
                verticalArrangement = Arrangement.spacedBy(16.dp),
                contentPadding = PaddingValues(bottom = 24.dp)
            ) {
                // Header
                item {
                    AIPlannerHeader()
                }

                // Main Trip Planner Input Form
                item {
                    MainTripPlannerCard(
                        destination = destination,
                        onDestinationChange = { destination = it; it },
                        startDate = startDate,
                        endDate = endDate,
                        onSelectDatesClick = { showDatePicker = true },
                        adultsCount = adultsCount,
                        onAdultsChange = { adultsCount = it },
                        childrenCount = childrenCount,
                        onChildrenChange = { childrenCount = it },
                        budget = budget,
                        onBudgetChange = { budget = it },
                        selectedPreferences = selectedPreferences.value,
                        onTogglePreference = { pref ->
                            val current = selectedPreferences.value.toMutableSet()
                            if (current.contains(pref)) current.remove(pref) else current.add(pref)
                            selectedPreferences.value = current
                        },
                        selectedStyle = selectedStyle,
                        onStyleSelect = { selectedStyle = it },
                        onGenerateClick = {
                            if (destination.isBlank()) {
                                Toast.makeText(context, "Please enter a destination.", Toast.LENGTH_SHORT).show()
                            } else {
                                viewModel.setFromLocation("Chennai")
                                viewModel.setDestination(destination)
                                viewModel.setTravelers(adultsCount + childrenCount)
                                viewModel.setBudget(budget)
                                val today = java.time.LocalDate.now()
                                viewModel.setDates(today.plusDays(1), today.plusDays(4))
                                selectedPreferences.value.forEach { viewModel.toggleInterest(it) }
                                viewModel.setTravelStyle(selectedStyle)
                                viewModel.generateTrip()
                                onGenerate()
                            }
                        }
                    )
                }

                // Loading Banner when generating plan
                if (isGenerating) {
                    item {
                        LaunchedEffect(Unit) {
                            kotlinx.coroutines.delay(1500)
                            isGenerating = false
                            isPlanGenerated = true
                        }
                        Card(
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(20.dp),
                            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.5f))
                        ) {
                            Column(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(24.dp),
                                horizontalAlignment = Alignment.CenterHorizontally
                            ) {
                                CircularProgressIndicator(color = MaterialTheme.colorScheme.primary)
                                Spacer(modifier = Modifier.height(12.dp))
                                Text("Creating your personalized trip...", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                                Text("Optimizing route, budget, and local attractions...", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                            }
                        }
                    }
                }

                // Generated AI Itinerary Result View
                if (isPlanGenerated && !isGenerating) {
                    item {
                        Card(
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(24.dp),
                            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                        ) {
                            Column(modifier = Modifier.padding(18.dp)) {
                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.SpaceBetween,
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Column {
                                        Text("TRIP OVERVIEW", style = MaterialTheme.typography.labelSmall, fontWeight = FontWeight.ExtraBold, color = MaterialTheme.colorScheme.primary)
                                        Text("🌄 $destination", style = MaterialTheme.typography.headlineSmall, fontWeight = FontWeight.Bold)
                                    }
                                    Surface(
                                        shape = RoundedCornerShape(10.dp),
                                        color = MaterialTheme.colorScheme.primaryContainer
                                    ) {
                                        Text("GENERATED", style = MaterialTheme.typography.labelSmall, fontWeight = FontWeight.Bold, modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp))
                                    }
                                }

                                Spacer(modifier = Modifier.height(8.dp))
                                Text("$startDate - $endDate • ${adultsCount + childrenCount} Travelers", style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Spacer(modifier = Modifier.height(10.dp))

                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.SpaceBetween
                                ) {
                                    Column {
                                        Text("Target Budget", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                        Text(budget, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                                    }
                                    Column {
                                        Text("Estimated Cost", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                        Text("₹8,500", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                                    }
                                    Column {
                                        Text("Potential Saving", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                        Text("₹3,500", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, color = Color(0xFF4CAF50))
                                    }
                                }

                                HorizontalDivider(modifier = Modifier.padding(vertical = 12.dp))

                                Text("DAY 1", style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.ExtraBold, color = MaterialTheme.colorScheme.secondary)
                                Text("• Chennai ➔ Ooty (Train / Private Cab - Estimated)", style = MaterialTheme.typography.bodySmall)
                                Text("• Hotel Check-in at Ooty View Resort (Estimated)", style = MaterialTheme.typography.bodySmall)
                                Text("• Ooty Lake Boat Ride (Entry fee ₹50 - Verified)", style = MaterialTheme.typography.bodySmall)

                                Spacer(modifier = Modifier.height(8.dp))
                                Text("DAY 2", style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.ExtraBold, color = MaterialTheme.colorScheme.secondary)
                                Text("• Botanical Garden & Tea Museum Tour", style = MaterialTheme.typography.bodySmall)
                                Text("• Doddabetta Peak Viewpoint", style = MaterialTheme.typography.bodySmall)

                                Spacer(modifier = Modifier.height(8.dp))
                                Text("DAY 3", style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.ExtraBold, color = MaterialTheme.colorScheme.secondary)
                                Text("• Coonoor Sightseeing & Sim's Park", style = MaterialTheme.typography.bodySmall)
                                Text("• Return journey to Chennai", style = MaterialTheme.typography.bodySmall)

                                Spacer(modifier = Modifier.height(14.dp))

                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                                ) {
                                    Button(
                                        onClick = {
                                            Toast.makeText(context, "Trip saved to My Trips!", Toast.LENGTH_SHORT).show()
                                        },
                                        modifier = Modifier.weight(1f),
                                        shape = RoundedCornerShape(12.dp)
                                    ) {
                                        Text("SAVE TRIP", fontWeight = FontWeight.Bold)
                                    }
                                    OutlinedButton(
                                        onClick = { isPlanGenerated = false },
                                        modifier = Modifier.weight(1f),
                                        shape = RoundedCornerShape(12.dp)
                                    ) {
                                        Text("EDIT PLAN", fontWeight = FontWeight.Bold)
                                    }
                                }
                            }
                        }
                    }

                    // Package vs Self-Plan Comparison
                    item {
                        SelfPlanVsPackageCard(
                            packageCost = 12000,
                            selfPlanCost = 8500,
                            onCompare = onNavigateToComparison
                        )
                    }
                }

                // Quick Tools
                item {
                    QuickToolsSection(
                        tools = quickTools
                    )
                }

                // Popular Itineraries
                item {
                    PopularItinerariesSection(
                        itineraries = popularItineraries,
                        onSelectItinerary = { item ->
                            destination = item.destination
                            isPlanGenerated = true
                        }
                    )
                }

                // Smart Tools Grid
                item {
                    SmartToolsGrid(
                        smartTools = smartTools,
                        onToolClick = { tool -> tool.onClick() }
                    )
                }

                // Ask AI Anything Banner
                item {
                    AskAIChatBanner(
                        onOpenChat = { showChatDialog = true }
                    )
                }
            }
        }
    }

    // Material 3 Date Picker Dialog
    if (showDatePicker) {
        DatePickerDialog(
            onDismissRequest = { showDatePicker = false },
            confirmButton = {
                TextButton(
                    onClick = {
                        val selectedMillis = datePickerState.selectedDateMillis
                        if (selectedMillis != null) {
                            val sdf = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
                            startDate = sdf.format(Date(selectedMillis))
                            endDate = sdf.format(Date(selectedMillis + 3 * 86400000L))
                        }
                        showDatePicker = false
                    }
                ) {
                    Text("OK", fontWeight = FontWeight.Bold)
                }
            },
            dismissButton = {
                TextButton(onClick = { showDatePicker = false }) {
                    Text("Cancel")
                }
            }
        ) {
            DatePicker(state = datePickerState)
        }
    }

    // Sub Tool Dialogs
    if (showBudgetEstimator) BudgetEstimatorDialog(destination = destination, onDismiss = { showBudgetEstimator = false })
    if (showRouteFinder) BestRouteFinderDialog(onDismiss = { showRouteFinder = false })
    if (showStayRecommender) StayRecommenderDialog(onDismiss = { showStayRecommender = false })
    if (showFoodRecommender) FoodRecommenderDialog(onDismiss = { showFoodRecommender = false })
    if (showWeather) WeatherForecastDialog(onDismiss = { showWeather = false })
    if (showLocalInsights) LocalInsightsDialog(onDismiss = { showLocalInsights = false })
    if (showPackingList) PackingListDialog(onDismiss = { showPackingList = false })
    if (showLanguageHelper) LanguageHelperDialog(onDismiss = { showLanguageHelper = false })
    if (showCurrencyConverter) CurrencyConverterDialog(onDismiss = { showCurrencyConverter = false })
    if (showOfflinePlan) OfflinePlanDialog(onDismiss = { showOfflinePlan = false })
    if (showChatDialog) AIChatDialog(onDismiss = { showChatDialog = false })
}
